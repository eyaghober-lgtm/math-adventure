export function tr(lang: Lang, key: Key): string {
  return S[key][lang === 'en' ? 0 : 1];
}

/** Marker used by explanations: ⟦ ... ⟧ is a math expression that is always rendered left-to-right. */
export const M = (s: string | number) => `⟦${s}⟧`;

export const ARABIC_DIGITS = /[٠-٩]/g;
export function parseNum(s: string): number | null {
  const norm = s
    .replace(ARABIC_DIGITS, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
    .replace(/[^\d]/g, '');
  if (norm === '') return null;
  return Number(norm);
}
